export const locales = ['fr', 'nl'] as const;
export type Locale = (typeof locales)[number];
export const isLocale = (v: string): v is Locale => (locales as readonly string[]).includes(v);

/** Segments d'URL traduits : /fr/tracteurs ↔ /nl/tractoren */
export const routes = {
  tractors: { fr: 'tracteurs', nl: 'tractoren' },
  machines: { fr: 'machines', nl: 'machines' },
  configurator: { fr: 'configurateur', nl: 'configurator' },
  quote: { fr: 'devis', nl: 'offerte' },
  account: { fr: 'mes-devis', nl: 'mijn-offertes' },
  privacy: { fr: 'confidentialite', nl: 'privacy' },
  terms: { fr: 'conditions', nl: 'voorwaarden' },
} as const;
export type RouteKey = keyof typeof routes;

export function href(locale: Locale, key: RouteKey, ...rest: (string | number)[]) {
  return ['', locale, routes[key][locale], ...rest.map(String)].join('/');
}

